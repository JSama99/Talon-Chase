"""Write the ontology's published artifacts from the code that defines it.

    python -m chase.ontology.build            # write them
    python -m chase.ontology.build --check    # exit 1 if any committed file is stale

Three files, all generated, none edited by hand:

    ontology/talon-chase.schema.json     closed JSON Schema (draft 2020-12)
    ontology/talon-chase.context.jsonld  JSON-LD context
    docs/ONTOLOGY.md                     the same, for people
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from chase.ontology.constraints import RULES
from chase.ontology.events import EVENT_PAYLOADS, RETIRED_PAYLOADS
from chase.ontology.schema import (
    ENUMS,
    GROUP_PURPOSE,
    GROUPS,
    ONTOLOGY_ID,
    ONTOLOGY_VERSION,
    SHAPES,
    build_context,
    build_schema,
    schema_sha256,
)

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = ROOT / "ontology" / "talon-chase.schema.json"
CONTEXT_PATH = ROOT / "ontology" / "talon-chase.context.jsonld"
DOC_PATH = ROOT / "docs" / "ONTOLOGY.md"


def _json(value: Any) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False) + "\n"


def _type(prop: dict[str, Any]) -> str:
    """A short, readable type for a schema property."""
    if "$ref" in prop:
        name = prop["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#{name.lower()})"
    if "anyOf" in prop:
        kinds = [_type(p) for p in prop["anyOf"]]
        return " or ".join(k for k in kinds if k != "null") + " or null"
    kind = prop.get("type")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind == "array":
        return f"list of {_type(prop.get('items', {}))}"
    if kind == "object" and "additionalProperties" in prop:
        values = prop["additionalProperties"]
        if isinstance(values, dict):
            return f"map to {_type(values)}"
    return kind or "any"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _fields_table(definition: dict[str, Any]) -> list[str]:
    lines = ["| Field | Type | Meaning |", "| --- | --- | --- |"]
    for name, prop in definition["properties"].items():
        marks = []
        if prop.get("x-ref"):
            target = prop["x-ref"]
            optional = " (optional)" if prop.get("x-ref-optional") else ""
            marks.append(f"→ [{target}](#{target.lower()}){optional}")
        if prop.get("x-sensitive"):
            marks.append("**sensitive**")
        meaning = prop.get("description", "")
        if marks:
            meaning = f"{meaning} {' · '.join(marks)}".strip()
        lines.append(f"| `{name}` | {_type(prop)} | {_cell(meaning)} |")
    return lines


def build_doc() -> str:
    schema = build_schema()
    defs = schema["$defs"]
    out = [
        "# Ontology",
        "",
        "<!-- Generated by `python -m chase.ontology.build`. Do not edit by hand. -->",
        "",
        "What Talon Chase knows about, how those things relate, and the rules they obey.",
        "The code is the source: `chase/domain/models.py` (entities and fields),",
        "`chase/ontology/events.py` (evidence payloads), `chase/ontology/constraints.py`",
        "(rules). This page and the two files under `ontology/` are generated from it,",
        "and a test fails if they fall behind.",
        "",
        "| | |",
        "| --- | --- |",
        f"| Version | `{ONTOLOGY_VERSION}` |",
        f"| Id | `{ONTOLOGY_ID}` |",
        f"| Schema SHA-256 | `{schema_sha256()}` |",
        "| Schema | [`ontology/talon-chase.schema.json`](../ontology/talon-chase.schema.json) |",
        "| JSON-LD context | [`ontology/talon-chase.context.jsonld`]"
        "(../ontology/talon-chase.context.jsonld) |",
        "",
        "## Principles",
        "",
        "* **Closed.** Every object lists all its fields; anything else is refused. Both",
        "  stores validate every record they save and every event they append.",
        "* **Typed references.** A field that holds an id names the entity it points at",
        "  (`x-ref`). An empty optional reference means none.",
        "* **Sensitive values are marked.** Fields marked sensitive (`x-sensitive`) hold",
        "  what a carrier must never be told: rates, pickup numbers, customers,",
        "  consignees. The outbound guard reads these marks; it has no list of its own.",
        "* **History is not rewritten.** Consent is a sequence of records, not a flag.",
        "  Evidence is a hash chain whose payloads have fixed shapes per kind.",
        "* **Rules hold across records.** Each has a stable id, is checked after every",
        "  test, and has a test that breaks it on purpose.",
        "* **Versioned and hashed.** Exports carry the version and the schema's",
        "  canonical SHA-256.",
        "",
        "## Groups",
        "",
        "| Group | Purpose | Members |",
        "| --- | --- | --- |",
    ]
    for group, members in GROUPS.items():
        names = ", ".join(f"[{c.__name__}](#{c.__name__.lower()})" for c in members)
        out.append(f"| {group} | {GROUP_PURPOSE[group]} | {names} |")

    for group, members in GROUPS.items():
        out += ["", f"## {group}", "", GROUP_PURPOSE[group]]
        for cls in members:
            definition = defs[cls.__name__]
            kind = "value type" if cls.__name__ in SHAPES else "entity"
            out += ["", f"### {cls.__name__}", "", f"*{kind}*"]
            if definition.get("description"):
                out += ["", definition["description"]]
            out += ["", *_fields_table(definition)]

    other_shapes = [
        n for n in SHAPES if not any(n == c.__name__ for g in GROUPS.values() for c in g)
    ]
    out += ["", "## Value types", "", "Stored inside an entity, never on their own."]
    for name in other_shapes:
        definition = defs[name]
        out += ["", f"### {name}"]
        if definition.get("description"):
            out += ["", definition["description"]]
        out += ["", *_fields_table(definition)]

    out += ["", "## Enumerations", ""]
    for enum in ENUMS:
        definition = defs[enum.__name__]
        values = ", ".join(f"`{v}`" for v in definition["enum"])
        description = definition.get("description", "")
        out += [f"### {enum.__name__}", ""]
        if description:
            out += [description, ""]
        out += [values, ""]

    out += [
        "## Evidence payloads",
        "",
        "Each evidence kind has exactly these payload fields, all required. See",
        "[EVIDENCE.md](EVIDENCE.md) for how events are chained and verified.",
        "",
        "| Kind | Payload |",
        "| --- | --- |",
    ]
    for kind, fields in sorted(EVENT_PAYLOADS.items()):
        shape = ", ".join(f"`{name}`: {token}" for name, token in fields.items())
        out.append(f"| `{kind}` | {shape} |")
    out += [
        "",
        "Retired kinds appear in older chains and verify as before; nothing records them",
        "now and stores refuse to append them.",
        "",
        "| Kind | Payload |",
        "| --- | --- |",
    ]
    for kind, fields in sorted(RETIRED_PAYLOADS.items()):
        shape = ", ".join(f"`{name}`: {token}" for name, token in fields.items())
        out.append(f"| `{kind}` | {shape} |")

    out += [
        "",
        "## Rules",
        "",
        "Checked by `chase.ontology.constraints.check_store(store)`, which returns every",
        "violation. The test suite runs all of them against every store it builds, and",
        "the synthetic evaluation requires zero.",
        "",
        "| Id | Rule |",
        "| --- | --- |",
    ]
    out += [f"| {r.id} | {_cell(r.title)} |" for r in RULES]
    out += [
        "",
        "## Changing the ontology",
        "",
        "1. Change the models, payloads or rules.",
        "2. Add an Alembic migration that carries existing data over and back.",
        "3. Bump `ONTOLOGY_VERSION`: patch for wording, minor for something new and",
        "   optional, major for anything an older reader would get wrong.",
        "4. Run `python -m chase.ontology.build` and commit the result.",
        "",
    ]
    return "\n".join(out)


def artifacts() -> dict[Path, str]:
    return {
        SCHEMA_PATH: _json(build_schema()),
        CONTEXT_PATH: _json(build_context()),
        DOC_PATH: build_doc(),
    }


def stale() -> list[Path]:
    return [
        path
        for path, text in artifacts().items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if any file is stale")
    args = parser.parse_args(argv)
    if args.check:
        old = stale()
        for path in old:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if old:
            print("run: python -m chase.ontology.build", file=sys.stderr)
        return 1 if old else 0
    for path, text in artifacts().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
